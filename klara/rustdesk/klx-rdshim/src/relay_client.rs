#[cfg(test)]
mod tests {
    use super::*;

    fn live_enabled() -> bool {
        std::env::var("KLX_LIVE_RELAY")
            .map(|v| !v.is_empty() && v != "0")
            .unwrap_or(false)
    }

    const LIVE_HOST: &str = "87.99.147.244";

    #[test]
    fn uuid_v4_format() {
        let u = generate_uuid_v4_string();
        // Standard length: 8-4-4-4-12 + 4 dashes = 36
        assert_eq!(u.len(), 36);
        let parts: Vec<&str> = u.split('-').collect();
        assert_eq!(parts.len(), 5);
        assert_eq!(parts[0].len(), 8);
        assert_eq!(parts[1].len(), 4);
        assert_eq!(parts[2].len(), 4);
        assert_eq!(parts[3].len(), 4);
        assert_eq!(parts[4].len(), 12);
        // Version 4 → 13th hex digit must be '4'
        assert_eq!(&u[14..15], "4");
    }

    /// **LIVE TEST**: requesting a relay session for a deliberately
    /// unknown peer id should produce a structured error — either
    /// `Refused` (customer-side rustdesk would have to be online to
    /// reject) or `Timeout` (hbbs forwards and waits, nothing comes
    /// back). Both prove the wire format works end-to-end.
    #[test]
    fn relay_session_unknown_peer_live() {
        if !live_enabled() {
            eprintln!("relay_session_unknown_peer_live: skipped");
            return;
        }
        let licence = crate::secure::SERVER_PUBKEY_BASE64;
        let peer_id = format!("klx-ckpt3-unknown-{}", std::process::id());
        let result = open_relay_session(
            LIVE_HOST,
            &peer_id,
            licence,
            Duration::from_millis(3000),
        );
        eprintln!("relay_session_unknown_peer_live: {result:?}");
        match result {
            Err(RelayError::Refused(_))
            | Err(RelayError::Timeout)
            | Err(RelayError::Protocol(_))
            | Err(RelayError::Io(_)) => {
                // Any structured error is acceptable — proves we round-
                // tripped a RequestRelay protobuf and either hbbs or the
                // (absent) customer replied or timed out cleanly.
            }
            Ok(session) => {
                // Possible if hbbs is configured to always grant relay
                // regardless of customer presence. In that case the
                // session is "half-open" — the relay is holding our
                // socket waiting for a customer that will never arrive.
                eprintln!(
                    "relay_session: unexpectedly succeeded for unknown peer, endpoint={}",
                    session.relay_endpoint
                );
            }
        }
    }
}
